"""
validation/report.py

Formats V1–V7 check results into a Markdown validation report and
writes it to outputs/validation_report.md.
"""

from __future__ import annotations

from pathlib import Path

from validation.checks import CheckResult


def _status(passed: bool) -> str:
    return "✅ PASS" if passed else "❌ FAIL"


def format_document_section(doc_name: str, all_results: dict[str, list[CheckResult]]) -> str:
    """Format all check results for one document as a Markdown section.

    Every check V1–V7 is always shown, even when the result list is empty.
    An empty result list means the check could not run — that is shown as FAIL
    with an explanatory message so the report never silently omits a check.
    """
    lines: list[str] = [f"\n## {doc_name}\n"]

    required_checks = ("V1", "V2", "V3", "V4", "V5", "V6", "V7")

    for check_id in required_checks:
        results = all_results.get(check_id, [])

        if not results:
            # Empty result list — explicit FAIL rather than silent omission.
            lines.append(f"\n### {check_id} — ❌ FAIL\n")
            lines.append(
                f"- ❌ No results produced for {check_id}. "
                "The check could not run — data may be missing or malformed."
            )
            continue

        overall = all(r.passed for r in results)
        lines.append(f"\n### {check_id} — {_status(overall)}\n")
        for r in results:
            icon = "✅" if r.passed else "❌"
            lines.append(f"- {icon} {r.detail}")

    return "\n".join(lines)


def write_validation_report(
    sections: list[str],
    output_dir: Path,
) -> None:
    """Write the complete validation report to output_dir/validation_report.md."""
    output_dir.mkdir(parents=True, exist_ok=True)
    report_path = output_dir / "validation_report.md"

    header = """# Validation Report — Kessler Industrietechnik GmbH

**Generated by:** `python validate.py outputs/`  
**Documents covered:** INV-01, INV-02, INV-03, INV-04, INV-05

---

## Key findings

- **INV-04 Pos 7 — V1 FAIL (document-originated error):**
  Printed line_total = 1284.52; calculated = 26 × 48.02 = 1248.52; difference = +36.00.
  This is a discrepancy in the source document, not an extraction error.
  The extractor stores the printed value as-is per BR-01.

- **INV-04 19% — V2 FAIL (document-originated error):**
  Sum of 19% line totals = 5249.22; printed net = 5213.22; difference = +36.00.
  Caused by the Pos 7 discrepancy above.

- **INV-05 V2 — passes by construction (not an independent check):**
  net_by_vat_rate values for INV-05 are derived from line-item sums because
  the modern layout prints only a combined "Summe netto". V2 compares derived
  values against themselves. This is not an independent verification against
  a printed per-rate net value.

---
"""

    body = "\n".join(sections)
    report_path.write_text(header + body + "\n", encoding="utf-8")
